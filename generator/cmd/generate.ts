import { SchemaConfiguration, clearAutoGeneratedSchemaRefs, saveAutoGeneratedSchemaRefs, generateSchemasWithCsharpGenerator, getCsharpGeneratorProviderNamespaces } from '../generate';
import colors from 'colors';
import { executeSynchronous } from '../utils';
import yargs from 'yargs';
import path from 'path';
import { createWriteStream } from 'fs';
import { finished } from 'stream/promises';
import stripAnsi from 'strip-ansi';
import { repoRoot } from '../constants';

const argsConfig = yargs(process.argv.slice(2))
  .strict()
  .option('provider-namespace', { type: 'string', desc: 'Generate only this provider namespace (e.g. "Microsoft.Compute"); omit to generate all providers' })
  .option('summary-log-path', { type: 'string', desc: 'The path to store generation summary information in Markdown' });

executeSynchronous(async () => {
    const args = await argsConfig.parseAsync();
    const available = await getCsharpGeneratorProviderNamespaces();
    const requestedNamespace = args['provider-namespace'];
    let providerNamespaces = available;
    if (requestedNamespace !== undefined) {
        const namespace = available.find(value => value.toLowerCase() === requestedNamespace.toLowerCase());
        if (!namespace) {
            throw new Error(`Provider namespace '${requestedNamespace}' has no pre-built Bicep types.`);
        }
        providerNamespaces = [namespace];
    }
    const summaryPath = path.resolve(repoRoot, args['summary-log-path'] ?? 'summary.log');
    const schemaConfigs: SchemaConfiguration[] = [];
    const logFileStream = createWriteStream(summaryPath, { flags: 'a' });
    const logFinished = finished(logFileStream);
    // Observe stream errors immediately, including errors emitted while generation is running.
    void logFinished.catch(error => {
        console.error(error);
        process.exitCode = 1;
    });
    const logOut = (line: string) => {
        process.stdout.write(`${line}\n`);
        logFileStream.write(`${stripAnsi(line)}\n`);
    };

    try {
        for (const providerNamespace of providerNamespaces) {
            try {
                await clearAutoGeneratedSchemaRefs([{ namespace: providerNamespace }]);
                const startTime = Date.now();
                const generatedSchemas = await generateSchemasWithCsharpGenerator(providerNamespace);
                schemaConfigs.push(...generatedSchemas);
                console.log(`Time taken to generate ${colors.green.italic(providerNamespace)} : ${Date.now() - startTime} ms.`);
                if (generatedSchemas.length === 0) {
                    logOut(`<details><summary>Skipped namespace '${providerNamespace}': no writable resource schemas were generated (C# generator).</summary></details>`);
                } else {
                    logOut(`<details><summary>Successfully generated types for namespace '${providerNamespace}' (C# generator).</summary></details>`);
                }
            } catch (error) {
                console.log(colors.red(`${(error as Error)?.stack || error}`));
                process.exitCode = 1;
                logOut(`<details><summary>Failed to generate types for namespace '${providerNamespace}' (C# generator).</summary>\n\n\`\`\`\n${error}\n\`\`\`\n</details>`);
                if (requestedNamespace !== undefined) {
                    throw error;
                }
            }
        }

        await saveAutoGeneratedSchemaRefs(schemaConfigs);
    } finally {
        logFileStream.end();
        await logFinished;
    }
});
