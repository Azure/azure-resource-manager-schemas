    [TestMethod]
    [TestCategory(BaselineHelper.BaselineTestCategory)]
    [EmbeddedFilesTestData(@"^Files/schemas/.*\.json$")]
    public void Schema_generation_works(EmbeddedFile embeddedFile)
    {
        var baselineFolder = BaselineFolder.BuildOutputFolder(TestContext, embeddedFile);
        var schemaFile = baselineFolder.GetBaselineFile(embeddedFile.FileName);

        var streamPathParts = embeddedFile.StreamPath.Split('/').Skip(2).ToArray();
        var apiVersion = streamPathParts[0];
        var providerNamespace = string.Join('/', streamPathParts[1..])[..^".json".Length];

        var typeProvider = new ResourceTypeProvider(new AzTypeLoader());
        var resourceTypes = typeProvider.GetResourceTypes()
            .Where(x => string.Equals(Utils.GetProviderNamespace(x.resourceType), providerNamespace, System.StringComparison.OrdinalIgnoreCase))
            .Where(x => string.Equals(x.apiVersion, apiVersion, System.StringComparison.OrdinalIgnoreCase))
            .Select(x => typeProvider.Get(x.resourceType, x.apiVersion))
            .ToArray();

        var schema = JsonSchemaGenerator.GenerateProviderSchema(providerNamespace, apiVersion, resourceTypes, sortProperties: false);

        schemaFile.WriteToOutputFolder(schema.ToJsonString(MainGenerator.SerializerOptions));
        schemaFile.ShouldHaveExpectedValue();
    }

    [TestMethod]
    [EmbeddedFilesTestData(@"^Files/schemas/.*\.json$")]
    public void Schema_definitions_do_not_contain_ref_cycles(EmbeddedFile embeddedFile)
    {
        var streamPathParts = embeddedFile.StreamPath.Split('/').Skip(2).ToArray();
        var apiVersion = streamPathParts[0];
        var providerNamespace = string.Join('/', streamPathParts[1..])[..^".json".Length];

        var typeProvider = new ResourceTypeProvider(new AzTypeLoader());
        var resourceTypes = typeProvider.GetResourceTypes()
            .Where(x => string.Equals(Utils.GetProviderNamespace(x.resourceType), providerNamespace, System.StringComparison.OrdinalIgnoreCase))
            .Where(x => string.Equals(x.apiVersion, apiVersion, System.StringComparison.OrdinalIgnoreCase))
            .Select(x => typeProvider.Get(x.resourceType, x.apiVersion))
            .ToArray();

        var schema = JsonSchemaGenerator.GenerateProviderSchema(providerNamespace, apiVersion, resourceTypes, sortProperties: false);
        var root = schema;

        if (root["definitions"] is not JsonObject definitions)
        {
            return;
        }

        var edgesByDefinition = new Dictionary<string, HashSet<string>>(System.StringComparer.OrdinalIgnoreCase);
        foreach (var (definitionName, definitionSchema) in definitions)
        {
            var edges = new HashSet<string>(System.StringComparer.OrdinalIgnoreCase);
            foreach (var target in EnumerateLocalDefinitionRefs(definitionSchema))
            {
                edges.Add(target);
            }
            edgesByDefinition[definitionName] = edges;
        }

        var cycles = FindCycles(edgesByDefinition)
            .Select(cycle => string.Join(" -> ", cycle))
            .ToArray();

        cycles.Should().BeEmpty(
            "schema definitions should not contain $ref cycles (provider={0}, apiVersion={1})\nDetected cycles:\n{2}",
            providerNamespace,
            apiVersion,
            string.Join("\n", cycles));
    }

    [TestMethod]
    [TestCategory(BaselineHelper.BaselineTestCategory)]
    [EmbeddedFilesTestData(@"^Files/common/autogeneratedResources\.json$")]
    public void Autogenerated_resources_works(EmbeddedFile embeddedFile)
    {
        var baselineFolder = BaselineFolder.BuildOutputFolder(TestContext, embeddedFile);
        var schemaFile = baselineFolder.GetBaselineFile(embeddedFile.FileName);

        var typeProvider = new ResourceTypeProvider(new AzTypeLoader());

        var providerBaselineRegex = new Regex(@"^Files/schemas/\d{4}-\d{2}-\d{2}(?:-(?:preview|privatepreview))?/.*\.json$", RegexOptions.Compiled);
        var embeddedProviders = GetType().Assembly
            .GetManifestResourceNames()
            .Where(name => providerBaselineRegex.IsMatch(name))
            .Select(name => name.Split('/').Skip(2).ToArray())
            .Select(parts => (
                apiVersion: parts[0],
                providerNamespace: string.Join('/', parts[1..])[..^".json".Length]))
            .Distinct()
            .ToArray();

        var refs = new List<AutogeneratedResourcesGenerator.ResourceRef>();

        foreach (var (apiVersion, providerNamespace) in embeddedProviders)
        {
            var resourceTypes = typeProvider.GetResourceTypes()
                .Where(x => string.Equals(Utils.GetProviderNamespace(x.resourceType), providerNamespace, System.StringComparison.OrdinalIgnoreCase))
                .Where(x => string.Equals(x.apiVersion, apiVersion, System.StringComparison.OrdinalIgnoreCase))
                .Select(x => typeProvider.Get(x.resourceType, x.apiVersion))
                .ToArray();

            foreach (var resourceType in resourceTypes)
            {
                var resourceTypeName = resourceType.Name.Split('@', 2)[0];
                var key = JsonSchemaGenerator.GetArmResourceDefinitionKey(resourceTypeName);

                refs.Add(new(apiVersion, providerNamespace, resourceType, key));
            }
        }

        var content = AutogeneratedResourcesGenerator.Generate([..refs]);
        schemaFile.WriteToOutputFolder(content.ToJsonString(MainGenerator.SerializerOptions));
        schemaFile.ShouldHaveExpectedValue();
    }

    [TestMethod]
    public void GetArmResourceDefinitionKey_sanitizes_unsafe_characters()
    {
        // Example: nested resource type segment contains '.' which breaks schema normalization if emitted into a definition key.
        var key = JsonSchemaGenerator.GetArmResourceDefinitionKey("Microsoft.Billing/billingPeriods/Microsoft.Consumption");

        Assert.AreEqual("billingPeriods_Microsoft_Consumption", key);
    }

    [TestMethod]
    [DataRow(false)]
    [DataRow(true)]
    public void Schema_generation_replaces_slashes_in_definition_keys_and_references(bool discriminated)
    {
        const string providerNamespace = "Microsoft.HorizonDb";
        const string apiVersion = "2026-10-01-preview";
        const string typeName = "microsoft.horizondb/clusters/authentications";
        const string definitionKey = "microsoft.horizondb_clusters_authentications";
        var factory = new TypeFactory([]);
        var stringType = factory.Create(() => new StringType());
        var variant = factory.Create(() => new ObjectType(
            typeName + "/variant",
            new Dictionary<string, ObjectTypeProperty>
            {
                ["value/part"] = new(factory.GetReference(stringType), ObjectTypePropertyFlags.Required, null),
            },
            additionalProperties: null));
        TypeBase type = discriminated
            ? factory.Create(() => new DiscriminatedObjectType(
                typeName,
                "kind",
                new Dictionary<string, ObjectTypeProperty>(),
                new Dictionary<string, ITypeReference> { ["example"] = factory.GetReference(variant) }))
            : variant;
        var expectedDefinitionKey = discriminated ? definitionKey : definitionKey + "_variant";
        var body = factory.Create(() => new ObjectType(
            providerNamespace + "/clusters",
            new Dictionary<string, ObjectTypeProperty>
            {
                ["payload/path"] = new(factory.GetReference(type), ObjectTypePropertyFlags.Required, null),
            },
            additionalProperties: null));
        var resource = new ResourceType(
            providerNamespace + "/clusters@" + apiVersion,
            factory.GetReference(body),
            functions: null,
            writableScopes_in: ScopeType.ResourceGroup,
            readableScopes_in: ScopeType.ResourceGroup);

        var schema = JsonSchemaGenerator.GenerateProviderSchema(providerNamespace, apiVersion, [resource], sortProperties: false);
        var definitions = schema["definitions"]!.AsObject();
        definitions.Select(definition => definition.Key).Should().NotContain(key => key.Contains('/'));
        definitions.ContainsKey(expectedDefinitionKey).Should().BeTrue();
        definitions[definitionKey + "_variant"]!["properties"]!["value/part"]!["type"]!
            .GetValue<string>().Should().Be("string");
        var resourceSchema = schema["resourceDefinitions"]!["clusters"]!;
        resourceSchema["properties"]!["payload/path"]!["oneOf"]![0]!["$ref"]!
            .GetValue<string>().Should().Be("#/definitions/" + expectedDefinitionKey);
        resourceSchema["required"]!.AsArray().Select(value => value!.GetValue<string>())
            .Should().Contain("payload/path");
        resourceSchema["properties"]!["type"]!["enum"]![0]!
            .GetValue<string>().Should().Be(providerNamespace + "/clusters");
        EnumerateLocalDefinitionRefs(schema).Should().OnlyContain(key => definitions.ContainsKey(key));
    }

    [TestMethod]
    public void Schema_generation_disambiguates_definition_keys_after_replacing_slashes()
    {
        const string providerNamespace = "Microsoft.Test";
        const string apiVersion = "2026-01-01";
        var factory = new TypeFactory([]);
        var properties = new Dictionary<string, ObjectTypeProperty>();
        foreach (var name in new[] { "Path/Type", "Path/Type_1", "Path_Type", "path_type" })
        {
            var value = factory.Create(() => new StringLiteralType(name));
            var type = factory.Create(() => new ObjectType(
                name,
                new Dictionary<string, ObjectTypeProperty>
                {
                    ["value"] = new(factory.GetReference(value), ObjectTypePropertyFlags.Required, null),
                },
                additionalProperties: null));
            properties.Add(name, new(factory.GetReference(type), ObjectTypePropertyFlags.Required, null));
        }
        var body = factory.Create(() => new ObjectType(providerNamespace + "/resources", properties, additionalProperties: null));
        var resource = new ResourceType(
            providerNamespace + "/resources@" + apiVersion,
            factory.GetReference(body),
            functions: null,
            writableScopes_in: ScopeType.ResourceGroup,
            readableScopes_in: ScopeType.ResourceGroup);

        var schema = JsonSchemaGenerator.GenerateProviderSchema(providerNamespace, apiVersion, [resource], sortProperties: false);
        var definitions = schema["definitions"]!.AsObject();
        definitions.Select(definition => definition.Key)
            .Should().BeEquivalentTo("Path_Type", "Path_Type_1", "Path_Type_2", "path_type_3");
        foreach (var name in properties.Keys)
        {
            var reference = schema["resourceDefinitions"]!["resources"]!["properties"]![name]!["oneOf"]![0]!["$ref"]!
                .GetValue<string>();
            var definition = definitions[reference["#/definitions/".Length..]]!;
            definition["properties"]!["value"]!["oneOf"]![0]!["enum"]![0]!
                .GetValue<string>().Should().Be(name);
        }
    }

    [TestMethod]
    public void Schema_generation_does_not_emit_Type_or_ApiVersion_case_variants()
    {
        var typeProvider = new ResourceTypeProvider(new AzTypeLoader());
        var resourceTypes = typeProvider.GetResourceTypes()
            .Where(x => string.Equals(Utils.GetProviderNamespace(x.resourceType), "Microsoft.Insights", System.StringComparison.OrdinalIgnoreCase))
            .Where(x => string.Equals(x.apiVersion, "2015-05-01", System.StringComparison.OrdinalIgnoreCase))
            .Select(x => typeProvider.Get(x.resourceType, x.apiVersion))
            .ToArray();

        var schema = JsonSchemaGenerator.GenerateProviderSchema("Microsoft.Insights", "2015-05-01", resourceTypes, sortProperties: false);
        var root = schema;

        var resourceDefinitions = root["resourceDefinitions"]!.AsObject();
        // This is one of the entries that historically had both "type" and "Type".
        var analyticsItems = resourceDefinitions["components_analyticsItems"]!.AsObject();
        var props = analyticsItems["properties"]!.AsObject();

        Assert.IsFalse(props.ContainsKey("Type"), "Should not emit 'Type' alongside reserved 'type'.");
        Assert.IsFalse(props.ContainsKey("ApiVersion"), "Should not emit 'ApiVersion' alongside reserved 'apiVersion'.");
    }

    [TestMethod]
    [DataRow("2017-09-01-preview")]
    public void Schema_generation_handles_discriminated_objects_without_variants(string apiVersion)
    {
        const string providerNamespace = "Microsoft.DataFactory";
        var typeProvider = new ResourceTypeProvider(new AzTypeLoader());
        var resourceTypes = typeProvider.GetResourceTypes()
            .Where(entry => string.Equals(Utils.GetProviderNamespace(entry.resourceType), providerNamespace, System.StringComparison.OrdinalIgnoreCase))
            .Where(entry => string.Equals(entry.apiVersion, apiVersion, System.StringComparison.OrdinalIgnoreCase))
            .Select(entry => typeProvider.Get(entry.resourceType, entry.apiVersion))
            .ToArray();

        var schema = JsonSchemaGenerator.GenerateProviderSchema(providerNamespace, apiVersion, resourceTypes, sortProperties: false);
        var copySink = schema["definitions"]!["CopySink"]!.AsObject();
        var discriminator = copySink["properties"]!["type"]!.AsObject();

        Assert.AreEqual("string", discriminator["type"]!.GetValue<string>());
        Assert.IsFalse(discriminator.ContainsKey("enum"));
        Assert.IsFalse(copySink.ContainsKey("oneOf"));
        Assert.IsFalse(copySink.ContainsKey("allOf"));
    }

    private static IEnumerable<string> EnumerateLocalDefinitionRefs(JsonNode? node)
    {
        if (node is null)
        {
            yield break;
        }

        if (node is JsonObject obj)
        {
            if (obj.TryGetPropertyValue("$ref", out var refNode) && refNode is JsonValue refValue)
            {
                var refString = refValue.GetValue<string>();
                const string prefix = "#/definitions/";
                if (refString.StartsWith(prefix, System.StringComparison.OrdinalIgnoreCase))
                {
                    yield return refString[prefix.Length..];
                }
            }

            foreach (var child in obj.Select(kvp => kvp.Value))
            {
                foreach (var r in EnumerateLocalDefinitionRefs(child))
                {
                    yield return r;
                }
            }

            yield break;
        }

        if (node is JsonArray arr)
        {
            foreach (var child in arr)
            {
                foreach (var r in EnumerateLocalDefinitionRefs(child))
                {
                    yield return r;
                }
            }
        }
    }

    private static IEnumerable<IReadOnlyList<string>> FindCycles(IReadOnlyDictionary<string, HashSet<string>> edgesByDefinition)
    {
        var visited = new HashSet<string>(System.StringComparer.OrdinalIgnoreCase);
        var stack = new Stack<string>();
        var onStack = new HashSet<string>(System.StringComparer.OrdinalIgnoreCase);
        var cycles = new List<IReadOnlyList<string>>();

        foreach (var start in edgesByDefinition.Keys)
        {
            if (!visited.Contains(start))
            {
                Dfs(start);
            }
        }

        return cycles;

        void Dfs(string node)
        {
            visited.Add(node);
            stack.Push(node);
            onStack.Add(node);

            if (edgesByDefinition.TryGetValue(node, out var edges))
            {
                foreach (var next in edges)
                {
                    if (!visited.Contains(next))
                    {
                        Dfs(next);
                        continue;
                    }

                    if (onStack.Contains(next))
                    {
                        // Materialize cycle path from 'next' up to current node.
                        var cycle = stack.Reverse().SkipWhile(x => !string.Equals(x, next, System.StringComparison.OrdinalIgnoreCase)).ToList();
                        cycle.Add(next);
                        cycles.Add(cycle);
                    }
                }
            }

            onStack.Remove(node);
            stack.Pop();
        }
    }
